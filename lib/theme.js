export function makeColors(name) {
  const [ink, deep, raised, line, sub, text] = PALETTES[name];
  return {
    name,
    bg: ink,
    card: deep,
    raised,
    line,
    text,
    sub,
    accent: ACCENTS[name],
    onAccent: ink,
    good: '#4CC38A',
    bad: '#E08A7E',
    warn: '#D9B26A',
    edge: 'rgba(255,255,255,0.06)', // тонкая светлая кромка карточек
    sleep: '#7FA7C9', // сон на графиках
    heart: '#E08A7E', // пульс на графиках
  };
}

